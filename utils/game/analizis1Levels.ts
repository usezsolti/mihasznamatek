function assertSixByTwenty(topicId: string, list: Question[]): void {
    const stages = [1, 2, 3, 4, 5, 6].map((s) => list.filter((q) => q.stage === s).length);
    if (list.length !== 120 || stages.some((n) => n !== 20)) {
        throw new Error(`${topicId}: ${list.length} cards stages=${stages.join(',')}`);
    }
}

export function getAnalizis1PracticeQuestions(topicId: string): Question[] | null {
    const rows = BANKS[topicId.toLowerCase()];
    if (!rows) return null;
    const list = bank(rows);
    assertSixByTwenty(topicId, list);
    return list;
}

export function getAllAnalizis1Banks(): Record<string, Question[]> {
    const out: Record<string, Question[]> = {};
    for (const id of ANALIZIS1_TOPIC_IDS) {
        out[id] = getAnalizis1PracticeQuestions(id) || [];
    }
    return out;
}

