function card(
    stage: PracticeStage,
    question: string,
    answer: number,
    expression: string,
    expectedSet?: string[]
): Question {
    return expectedSet
        ? { stage, question, answer, type: T, expression, expectedSet }
        : { stage, question, answer, type: T, expression };
}

type Row = [PracticeStage, string, number, string] | [PracticeStage, string, number, string, string[]];

function bank(rows: Row[]): Question[] {
    return rows.map((r) => card(r[0], r[1], r[2], r[3], r[4]));
}

