const TABLES: Record<Lang, Dict> = { hu, en };

type LangCtx = {
    lang: Lang;
    setLang: (lang: Lang) => void;
    toggleLang: () => void;
    t: (key: string, vars?: Record<string, string>) => string;
};

const LanguageContext = createContext<LangCtx | null>(null);

function readStoredLang(): Lang {
    if (typeof window === 'undefined') return 'hu';
    try {
        const v = localStorage.getItem(STORAGE_KEY);
        if (v === 'en' || v === 'hu') return v;
    } catch {
        /* ignore */
    }
    return 'hu';
}

export function LanguageProvider({ children }: { children: ReactNode }) {
    const [lang, setLangState] = useState<Lang>('hu');
    const [ready, setReady] = useState(false);

    useEffect(() => {
        const next = readStoredLang();
        setLangState(next);
        setReady(true);
        document.documentElement.lang = next;
    }, []);

    const setLang = useCallback((next: Lang) => {
        setLangState(next);
        try {
            localStorage.setItem(STORAGE_KEY, next);
        } catch {
            /* ignore */
        }
        if (typeof document !== 'undefined') {
            document.documentElement.lang = next;
        }
    }, []);

    const toggleLang = useCallback(() => {
        setLang(lang === 'hu' ? 'en' : 'hu');
    }, [lang, setLang]);

    const t = useCallback(
        (key: string, vars?: Record<string, string>) => {
            const table = TABLES[lang] || hu;
            let out = table[key] || hu[key] || key;
            if (vars) {
                for (const [k, v] of Object.entries(vars)) {
                    out = out.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
                }
            }
            return out;
        },
        [lang]
    );

    const value = useMemo(
        () => ({ lang, setLang, toggleLang, t }),
        [lang, setLang, toggleLang, t]
    );

    // Avoid flashing wrong language on first paint for hydrated clients
    if (!ready && typeof window !== 'undefined') {
        /* still render — default hu until effect runs */
    }

    return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLang(): LangCtx {
    const ctx = useContext(LanguageContext);
    if (!ctx) {
        return {
            lang: 'hu',
            setLang: () => undefined,
            toggleLang: () => undefined,
            t: (key, vars) => {
                let out = hu[key] || key;
                if (vars) {
                    for (const [k, v] of Object.entries(vars)) {
                        out = out.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
                    }
                }
                return out;
            },
        };
    }
    return ctx;
}
